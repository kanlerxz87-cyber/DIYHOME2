#!/usr/bin/env python3
"""Render the independent-review table on audit/index.html from data/discrepancies.json.

The audit page is hand-maintained HTML, so nothing forced its review table to agree
with the record behind it. This script owns exactly one block between the two
REVIEW-TABLE markers; everything else on the page is left untouched. Idempotent:
running it twice produces the same bytes.

    python3 scripts/render_review.py           # rewrite the block
    python3 scripts/render_review.py --check   # exit 1 if the page has drifted

Amazon listing and redirector URLs are printed as text, never as links: an untagged
Amazon link on a page is what F12 records, and repeating it here would add to it.
"""
import html
import json
import sys
from pathlib import Path

START = '<!-- REVIEW-TABLE:START (generated by scripts/render_review.py from data/discrepancies.json) -->'
END = '<!-- REVIEW-TABLE:END -->'
PAGE = Path('audit/index.html')
DATA = Path('data/discrepancies.json')


def is_listing(url: str) -> bool:
    return 'www.amazon.com/dp/' in url or 'link.amazon/' in url


def render() -> str:
    doc = json.loads(DATA.read_text())
    e = lambda s: html.escape(str(s), quote=True)
    out = [START]
    for r in doc['rows']:
        if is_listing(r['url']):
            src = f'<code>{e(r["url"])}</code> <small>(listing, not linked: untagged)</small>'
        else:
            src = f'<a href="{e(r["url"])}">{e(r["url"].split("//", 1)[1])}</a>'
        out.append(
            f'''            <tr id="rev-{e(r['id'])}">
              <td><code>{e(r['id'])}</code> · <a href="../sources.html#src-{e(r['source'])}">{e(r['source'])}</a></td>
              <td>{e(r['document'])}<br><small>{e(r['section'])}</small></td>
              <td>{e(r['dated_on_page'])}<br><small>read {e(r['read_at'])}</small></td>
              <td>{e(r['verdict'])}</td>
              <td>{e(r['effect'])}</td>
              <td>{src}</td>
            </tr>''')
    out.append('            ' + END)
    return '\n'.join(out)


def splice(page: str, block: str) -> str:
    i, j = page.find(START), page.find(END)
    if i < 0 or j < 0:
        sys.exit('audit/index.html has no REVIEW-TABLE markers; refusing to guess where the table goes')
    return page[:i] + block + page[j + len(END):]


def main() -> None:
    page = PAGE.read_text()
    new = splice(page, render())
    if '--check' in sys.argv:
        if new != page:
            sys.exit('audit/index.html review table has drifted from data/discrepancies.json; run scripts/render_review.py')
        print(f'review table matches data/discrepancies.json ({json.loads(DATA.read_text())["rows"].__len__()} rows)')
        return
    if new != page:
        PAGE.write_text(new)
        print('rewrote the review table from data/discrepancies.json')
    else:
        print('review table already current')


if __name__ == '__main__':
    main()
